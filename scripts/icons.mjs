// Copies the game-icons.net icons we use into src/ui/icons.data.ts (only these, so the bundle stays small).
// Icons by Lorc, Delapouite and contributors, https://game-icons.net, CC BY 3.0.
// To add one: find its name on game-icons.net (the last part of the URL), add it below, run `node scripts/icons.mjs`.
import { readFileSync, writeFileSync } from 'fs';
const NAMES = [
  // item slots + "everything"
  'broadsword', 'visored-helm', 'breastplate', 'gauntlet', 'trousers', 'leather-boot', 'rune-stone', 'cape', 'knapsack', 'swap-bag',
  // stats and currencies
  'hearts', 'sword-wound', 'bullseye', 'checked-shield', 'cog', 'metal-bar', 'padlock',
  // run doors: rewards and danger
  'two-coins', 'upgrade', 'heart-plus', 'chest', 'open-book', 'daemon-skull', 'crowned-skull', 'death-skull',
  // notice board: tabs, categories, reasons, records
  'target-arrows', 'stairs-goal', 'abacus', 'laurels-trophy', 'calculator', 'divided-square', 'flame', 'pin',
  'hourglass', 'sparkles', 'broken-shield', 'rank-3',
  // camp stations
  'anvil-impact', 'archery-target', 'scroll-quill', 'meditation', 'open-gate',
  // skills
  'explosion-rays', 'magic-shield', 'health-increase', 'lightning-branches', 'frozen-orb', 'executioner-hood', 'third-eye', 'meteor-impact', 'time-trap',
  // passives
  'sword-slice', 'battery-pack', 'stone-wall', 'eye-target', 'brain',
  // run powers
  'sword-clash', 'fast-arrow', 'piercing-sword', 'run', 'heart-drop', 'magic-swirl', 'stopwatch',
  // app: install hint, save backup
  'smartphone', 'save',
];
const all = JSON.parse(readFileSync(new URL('../node_modules/@iconify-json/game-icons/icons.json', import.meta.url))).icons;
const missing = NAMES.filter(n => !all[n]);
if (missing.length) { console.error('unknown icons:', missing.join(', ')); process.exit(1); }
const lines = NAMES.map(n => `  '${n}': ${JSON.stringify(all[n].body)},`);
writeFileSync(new URL('../src/ui/icons.data.ts', import.meta.url), `// Generated by scripts/icons.mjs from game-icons.net (CC BY 3.0). Don't edit by hand.\nexport const ICON_BODIES = {\n${lines.join('\n')}\n} as const;\n`);
console.log(`wrote ${NAMES.length} icons`);
