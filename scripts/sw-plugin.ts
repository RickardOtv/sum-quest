/**
 * Vite plugin: after `npm run build`, writes dist/sw.js, the service worker that
 * keeps an offline copy of the game. Its file list (and version) comes from the
 * build itself, so every deploy automatically replaces the old copy.
 *
 * How it behaves on the phone:
 * - the page (index.html) is fetched fresh when online, so updates show up on the next start;
 *   offline, the saved copy is used
 * - everything else (code, fonts, images) comes from the saved copy, instantly
 * (.woff fonts are skipped: phones use the smaller .woff2 ones)
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Plugin } from 'vite';

const SKIP = new Set(['sw.js', 'version.json', '_headers', '_redirects']);

function filesIn(dir: string, root = dir): string[] {
  return readdirSync(dir).flatMap(name => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? filesIn(p, root) : [relative(root, p).split('\\').join('/')];
  });
}

export function serviceWorker(outDir: string, buildId: string): Plugin {
  return {
    name: 'sumquest-service-worker',
    apply: 'build',
    closeBundle() {
      // version.json: the app fetches it to notice when a newer build is live (see src/pwa.ts)
      writeFileSync(join(outDir, 'version.json'), JSON.stringify({ build: buildId }) + '\n');
      const files = filesIn(outDir).filter(f => !SKIP.has(f));
      const hash = createHash('sha256');
      for (const f of files.sort()) hash.update(f).update(readFileSync(join(outDir, f)));
      const version = hash.digest('hex').slice(0, 12);
      const list = ['./', ...files.filter(f => f !== 'index.html' && !f.endsWith('.woff')).map(f => './' + f)];
      writeFileSync(join(outDir, 'sw.js'), `// Generated by scripts/sw-plugin.ts at build time. Don't edit.
const CACHE = 'sumquest-${version}';
const FILES = ${JSON.stringify(list)};

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('sumquest-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin || url.pathname.endsWith('/version.json')) return; // the version check always asks the server
  if (req.mode === 'navigate') { // the page: fresh when online, saved copy when offline
    e.respondWith(fetch(req).then(res => { const copy = res.clone(); caches.open(CACHE).then(c => c.put('./', copy)); return res; })
      .catch(() => caches.match('./')));
    return;
  }
  e.respondWith(caches.match(req).then(hit => hit || fetch(req).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return res;
  })));
});
`);
    },
  };
}
